"""Builds assets/voice/sprite.m4a and voiceSprite.ts from the clips in voice-src/.

Why one file: phones only let a web page start sound from a tap, and iPhones ignore
volume changes made by the page. One file started by the Start tap avoids both problems,
and every clip is leveled here, in the audio itself, to the quiet "Breathe in" cue.

Run on a Mac from the project folder:  python3 scripts/build_voice.py
"""
import glob, math, os, struct, subprocess, tempfile, wave

SR = 44100
TARGET_DB = -29.5      # speech level of the "Breathe in" cue everyone liked
GAP = 1.2              # silence between clips, seconds
LEAD = 1.0             # silence at the very start of the file

def read_mp3(path, tmp):
    wav = os.path.join(tmp, os.path.basename(path) + '.wav')
    subprocess.run(['afconvert', '-f', 'WAVE', '-d', 'LEI16@%d' % SR, '-c', '1', path, wav], check=True)
    w = wave.open(wav); n = w.getnframes()
    return [x / 32768 for x in struct.unpack('<%dh' % n, w.readframes(n))]

def speech_db(d):
    fl = int(SR * 0.02); sq = []
    for i in range(0, len(d) - fl, fl):
        r = sum(x * x for x in d[i:i + fl]) / fl
        if r > (200 / 32768) ** 2: sq.append(r)
    return 10 * math.log10(sum(sq) / len(sq)) if sq else -99

def trim(d, pad=0.08):
    thr = 10 ** (-48 / 20); a = 0; b = len(d)
    while a < b and abs(d[a]) < thr: a += 1
    while b > a and abs(d[b - 1]) < thr: b -= 1
    p = int(pad * SR)
    return d[max(0, a - p):min(len(d), b + p)]

def fade(d, sec=0.02):
    n = min(int(sec * SR), len(d) // 2)
    for i in range(n):
        d[i] *= i / n; d[-1 - i] *= i / n
    return d

def tones():
    out = [0.0] * int(SR * 3.0)
    for k in range(3):
        s = k * SR
        for i in range(int(SR * 0.9)):
            t = i / SR
            env = min(1.0, t / 0.06) * math.exp(-t * 3.2)   # soft attack, slow fade
            out[s + i] += 0.085 * env * (math.sin(2 * math.pi * 196 * t) + 0.25 * math.sin(2 * math.pi * 392 * t))
    return out

def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    clips = {}
    with tempfile.TemporaryDirectory() as tmp:
        for p in sorted(glob.glob(os.path.join(root, 'voice-src', '*.mp3'))):
            key = os.path.basename(p)[:-4]
            d = trim(read_mp3(p, tmp))
            gain = 10 ** ((TARGET_DB - speech_db(d)) / 20)
            clips[key] = fade([max(-1, min(1, x * gain)) for x in d])
        clips['tones'] = tones()
        out = [0.0] * int(LEAD * SR); index = {}
        for key in sorted(clips):
            index[key] = (len(out) / SR, len(clips[key]) / SR)
            out += clips[key] + [0.0] * int(GAP * SR)
        wav = os.path.join(tmp, 'sprite.wav')
        w = wave.open(wav, 'w'); w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes(b''.join(struct.pack('<h', int(x * 32767)) for x in out)); w.close()
        os.makedirs(os.path.join(root, 'assets', 'voice'), exist_ok=True)
        subprocess.run(['afconvert', '-f', 'm4af', '-d', 'aac', '-b', '72000', wav,
                        os.path.join(root, 'assets', 'voice', 'sprite.m4a')], check=True)
    lines = ['// Generated by scripts/build_voice.py. Do not edit by hand.',
             "export const SPRITE_SRC = require('./assets/voice/sprite.m4a');",
             '// key: [start, length] in seconds within the one audio file',
             'export const SPRITE: Record<string, [number, number]> = {']
    for key in sorted(index):
        lines.append("  '%s': [%.2f, %.2f]," % (key, index[key][0], index[key][1]))
    lines.append('};')
    open(os.path.join(root, 'voiceSprite.ts'), 'w').write('\n'.join(lines) + '\n')
    print('%d clips, %.0f seconds' % (len(index), len(out) / SR))

main()
